MOCK_WARNING = "MOCK ASSET: not generated by a production AI model"


def _provenance(provider: str, latency: float, **configuration: object) -> Provenance:
    return Provenance(
        provider=provider,
        model_identifier="deterministic-mock",
        checkpoint_revision="mock-v1",
        model_configuration=configuration,
        generation_latency_seconds=latency,
        warnings=(MOCK_WARNING,),
    )


class MockSpeechGenerator:
    async def generate(self, request: SpeechGenerationRequest) -> GeneratedAsset:
        started = time.perf_counter()
        duration = request.requested_duration_seconds or max(1.0, len(request.text.split()) / 2.6)
        output = Path(request.context.work_dir) / f"{request.context.scene_id}-speech.wav"
        output.parent.mkdir(parents=True, exist_ok=True)
        await asyncio.to_thread(self._write_wave, output, duration, request.sample_rate)
        digest = file_sha256(output)
        return GeneratedAsset(
            asset_id=asset_id("aud", digest),
            kind=AssetKind.AUDIO,
            uri=str(output.resolve()),
            content_hash=digest,
            project_id=request.context.project_id,
            scene_id=request.context.scene_id,
            duration_seconds=duration,
            sample_rate=request.sample_rate,
            mime_type="audio/wav",
            provenance=_provenance(
                "mock-speech", time.perf_counter() - started, voice_id=request.voice_id
            ),
        )

    @staticmethod
    def _write_wave(output: Path, duration: float, sample_rate: int) -> None:
        frames = int(duration * sample_rate)
        with wave.open(str(output), "wb") as target:
            target.setnchannels(1)
            target.setsampwidth(2)
            target.setframerate(sample_rate)
            for index in range(frames):
                envelope = min(
                    1.0, index / (sample_rate * 0.05), (frames - index) / (sample_rate * 0.05)
                )
                sample = int(
                    1000 * max(0, envelope) * math.sin(2 * math.pi * 220 * index / sample_rate)
                )
                target.writeframesraw(struct.pack("<h", sample))


class MockImageGenerator:
    async def generate(self, request: VisualGenerationRequest) -> GeneratedAsset:
        started = time.perf_counter()
        output = Path(request.context.work_dir) / f"{request.context.scene_id}-visual.ppm"
        output.parent.mkdir(parents=True, exist_ok=True)
        await asyncio.to_thread(
            self._write_ppm, output, request.width, request.height, request.prompt
        )
        digest = file_sha256(output)
        return GeneratedAsset(
            asset_id=asset_id("img", digest),
            kind=AssetKind.IMAGE,
            uri=str(output.resolve()),
            content_hash=digest,
            project_id=request.context.project_id,
            scene_id=request.context.scene_id,
            width=request.width,
            height=request.height,
            mime_type="image/x-portable-pixmap",
            provenance=Provenance(
                provider="mock-image",
                model_identifier="deterministic-mock",
                checkpoint_revision="mock-v1",
                model_configuration={"width": request.width, "height": request.height},
                seed=request.seed,
                prompt=request.prompt,
                negative_prompt=request.negative_prompt,
                generation_latency_seconds=time.perf_counter() - started,
                warnings=(MOCK_WARNING,),
            ),
        )

    @staticmethod
    def _write_ppm(output: Path, width: int, height: int, prompt: str) -> None:
        seed_bytes = hashlib.sha256(prompt.encode()).digest()
        base = seed_bytes[:3]
        with output.open("wb") as target:
            target.write(f"P6\n{width} {height}\n255\n".encode())
            for y in range(height):
                row = bytearray()
                for x in range(width):
                    row.extend(
                        (
                            (base[0] + x * 91 // max(1, width)) % 256,
                            (base[1] + y * 113 // max(1, height)) % 256,
                            (base[2] + (x + y) * 47 // max(1, width + height)) % 256,
                        )
                    )
                target.write(row)


