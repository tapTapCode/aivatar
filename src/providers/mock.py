class MockAvatarSourceProvider:
    async def resolve(self, request: AvatarSourceRequest) -> GeneratedAsset:
        started = time.perf_counter()
        output = Path(request.context.work_dir) / f"{request.context.scene_id}-avatar.mp4"
        output.parent.mkdir(parents=True, exist_ok=True)
        await asyncio.to_thread(self._create_avatar, output, request)
        digest = file_sha256(output)
        return GeneratedAsset(
            asset_id=asset_id("avatar", digest),
            kind=AssetKind.AVATAR_SOURCE,
            uri=str(output.resolve()),
            content_hash=digest,
            project_id=request.context.project_id,
            scene_id=request.context.scene_id,
            duration_seconds=request.duration_seconds,
            width=request.width,
            height=request.height,
            fps=request.fps,
            mime_type="video/mp4",
            provenance=_provenance(
                "mock-avatar-source",
                time.perf_counter() - started,
                avatar_id=request.avatar_id,
            ),
        )

    @staticmethod
    def _create_avatar(output: Path, request: AvatarSourceRequest) -> None:
        ffmpeg = shutil.which("ffmpeg")
        if not ffmpeg:
            raise RuntimeError("ffmpeg is required for mock avatar generation")
        size = f"{request.width}x{request.height}"
        face_w = max(80, request.width // 3)
        face_h = max(100, request.height // 2)
        face_x = (request.width - face_w) // 2
        face_y = max(20, request.height // 8)
        mouth_y = face_y + int(face_h * 0.72)
        left_eye_x = face_x + face_w // 5
        right_eye_x = face_x + face_w * 3 // 5
        eye_y = face_y + face_h // 3
        eye_w = face_w // 7
        eye_h = face_h // 14
        mouth_x = face_x + face_w // 3
        mouth_w = face_w // 3
        mouth_h = max(8, face_h // 24)
        filters = (
            f"drawbox=x={face_x}:y={face_y}:w={face_w}:h={face_h}:color=0xE0A080:t=fill,"
            f"drawbox=x={left_eye_x}:y={eye_y}:w={eye_w}:h={eye_h}:color=0x202020:t=fill,"
            f"drawbox=x={right_eye_x}:y={eye_y}:w={eye_w}:h={eye_h}:color=0x202020:t=fill,"
            f"drawbox=x={mouth_x}:y={mouth_y}:w={mouth_w}:h={mouth_h}:color=0x7F1D1D:t=fill"
        )
        command = [
            ffmpeg,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-f",
            "lavfi",
            "-i",
            f"color=c=0x1F4C78:s={size}:r={request.fps}:d={request.duration_seconds}",
            "-vf",
            filters,
            "-c:v",
            "libx264",
            "-pix_fmt",
            "yuv420p",
            str(output),
        ]
        subprocess.run(command, check=True, capture_output=True)


